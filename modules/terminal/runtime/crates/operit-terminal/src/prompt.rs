//! Prompt emission: the host-side `ENV` / `PROMPT_COMMAND` policy.
//!
//! Kong keeps its own OSC 777 wire format (`\x1b]777;operit-prompt;<cwd>\x07`), parsed
//! host-side by `ShellPromptStream.kt`. Only the *delivery* matches Operit2: a host-set
//! environment variable, never a rewritten `/etc/profile`.
//!
//! * ash (Alpine, busybox): `ENV=/etc/operit/prompt.sh`; the file sets `PS1` only and
//!   never sources a profile (ash reads `$ENV` for interactive non-login shells).
//! * bash: `PROMPT_COMMAND` prints the marker before each prompt (Operit2
//!   `terminal.rs:1648-1650`).

/// `ENV` value written into the guest environment (absolute guest path).
pub const ASH_PROMPT_PATH: &str = "/etc/operit/prompt.sh";
/// The same file, relative to the rootfs root.
pub const ASH_PROMPT_RELATIVE: &str = "etc/operit/prompt.sh";
/// Inline `printf` used for bash; the `%s` is the live `$PWD`.
pub const BASH_PROMPT_COMMAND: &str = "printf '\\033]777;operit-prompt;%s\\007' \"$PWD\"";
/// Fallback prompt text for bash distros; the real cwd marker is emitted by
/// [`BASH_PROMPT_COMMAND`] and consumed by `ShellPromptStream`.
pub const BASH_PS1: &str = "$PWD $ ";

/// `PS1` file read through `ENV` by interactive ash.
///
/// This is the byte-identical port of `GuestRootfsPrep.ashPromptScript()` (pinned by
/// `GuestRootfsPrepTest.kt`). It must stay free of `source` / `. /etc/profile`:
/// Alpine's `/etc/profile` sources `/etc/profile.d/*.sh`, and a login shell that read
/// this file back from the profile would loop profile → file → profile.
pub fn ash_prompt_script() -> String {
    concat!(
        "# Generated by Operit. Read through ENV for interactive ash; never sourced by /etc/profile.\n",
        "# Do not source /etc/profile here: Alpine's profile sources /etc/profile.d/*.sh and the\n",
        "# login shell would loop profile -> this file -> profile.\n",
        "__operit_marker=\"$(printf '\\033]777;operit-prompt;')\"\n",
        "__operit_bel=\"$(printf '\\007')\"\n",
        "PS1=\"${__operit_marker}\"'${PWD}'\"${__operit_bel} \\$ \"\n",
    )
    .to_string()
}

/// Prompt environment variables for the given distro kind.
///
/// Alpine (busybox ash) has no `PROMPT_COMMAND`, so the file referenced by `ENV` owns
/// `PS1`. Every bash-like distro (`debian`, `ubuntu`, ...) gets the inline
/// `PROMPT_COMMAND` plus a plain `PS1`.
pub fn environment_for(distro: &str) -> Vec<(String, String)> {
    if distro.trim().to_ascii_lowercase().starts_with("alpine") {
        vec![("ENV".to_string(), ASH_PROMPT_PATH.to_string())]
    } else {
        vec![
            ("PROMPT_COMMAND".to_string(), BASH_PROMPT_COMMAND.to_string()),
            ("PS1".to_string(), BASH_PS1.to_string()),
        ]
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ash_script_is_byte_identical_to_the_reviewed_hook() {
        let expected = [
            "# Generated by Operit. Read through ENV for interactive ash; never sourced by /etc/profile.",
            "# Do not source /etc/profile here: Alpine's profile sources /etc/profile.d/*.sh and the",
            "# login shell would loop profile -> this file -> profile.",
            "__operit_marker=\"$(printf '\\033]777;operit-prompt;')\"",
            "__operit_bel=\"$(printf '\\007')\"",
            "PS1=\"${__operit_marker}\"'${PWD}'\"${__operit_bel} \\$ \"",
        ]
        .join("\n")
            + "\n";
        assert_eq!(expected, ash_prompt_script());
    }

    #[test]
    fn ash_script_emits_the_777_marker_and_never_sources_the_profile() {
        let script = ash_prompt_script();
        assert!(script.contains("]777;operit-prompt;"), "{script}");
        assert!(script.contains("'${PWD}'"), "{script}");
        for line in script.lines() {
            let trimmed = line.trim_start();
            assert!(
                !trimmed.starts_with('.') && !trimmed.starts_with("source"),
                "prompt file must not source a profile: {line}"
            );
        }
        assert!(!script.contains("/etc/profile\"]"));
    }

    #[test]
    fn bash_prompt_command_is_the_inline_printf_marker() {
        assert_eq!(
            "printf '\\033]777;operit-prompt;%s\\007' \"$PWD\"",
            BASH_PROMPT_COMMAND
        );
        assert!(!BASH_PROMPT_COMMAND.contains("/etc/profile"));
    }

    #[test]
    fn alpine_uses_env_others_use_bash_prompt() {
        assert_eq!(
            vec![("ENV".to_string(), ASH_PROMPT_PATH.to_string())],
            environment_for("alpine")
        );
        assert_eq!(
            vec![("ENV".to_string(), ASH_PROMPT_PATH.to_string())],
            environment_for("Alpine")
        );
        assert_eq!(
            vec![
                ("PROMPT_COMMAND".to_string(), BASH_PROMPT_COMMAND.to_string()),
                ("PS1".to_string(), BASH_PS1.to_string()),
            ],
            environment_for("debian")
        );
    }
}
